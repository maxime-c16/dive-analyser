import { test, expect, type Page } from '@playwright/test'
const nav = (page: Page) => page.locator('.mobile-tab-bar')
const open = (page:Page, query = '') => page.goto(`/e2e/fixtures/navigation-review.html?${query}`)
const go = (page:Page, path:string) => page.evaluate(path => (window as any).reviewRouter.navigate(path), path)
const offset = (page:Page) => page.evaluate(() => parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--mobile-nav-offset')))
for (const lang of ['fr','en']) for (const width of [320,390,430,767,768,1023,1366,1440]) {
  test(`${lang} ${width}px labels, active link, offset, last content`, async ({page}) => {
    await page.setViewportSize({width,height:844}); await open(page,`lang=${lang}&long=1`)
    await expect(page.getByRole('heading',{name:lang==='fr'?'Bibliothèque':'Library',level:1})).toBeVisible()
    if (width>=1024) { await expect(nav(page)).toHaveCount(0);expect(await offset(page)).toBe(0);return }
    await expect(nav(page)).toBeVisible();expect(await offset(page)).toBeGreaterThan(60)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBe(0)
    await expect(nav(page).getByRole('link')).toHaveCount(4)
    await expect(nav(page).getByRole('link',{name:lang==='fr'?'Bibliothèque':'Library'})).toHaveAttribute('aria-current','page')
    const geometry = await nav(page).locator('a').evaluateAll(links => links.map(link => { const r=link.getBoundingClientRect();const label=link.querySelector('span')!.getBoundingClientRect();return {width:r.width,height:r.height,contained:label.left>=r.left&&label.right<=r.right,visible:getComputedStyle(link.querySelector('span')!).display!=='none'} }))
    for(const item of geometry){expect(item.width).toBeGreaterThanOrEqual(48);expect(item.height).toBeGreaterThanOrEqual(48);expect(item.contained).toBe(true);expect(item.visible).toBe(true)}
    await page.evaluate(()=>window.scrollTo(0,document.documentElement.scrollHeight));await page.waitForTimeout(50)
    const last=page.getByRole('button',{name:/Open 103B attempt|Ouvrir.*103B/}).last()
    await expect(last).toBeVisible()
    expect(await last.evaluate(el => {const r=el.getBoundingClientRect();return el.contains(document.elementFromPoint(r.x+r.width/2,r.bottom-4))})).toBe(true)
    expect(await last.evaluate(el=>el.getBoundingClientRect().bottom)).toBeLessThan(await nav(page).evaluate(el=>el.getBoundingClientRect().top))
  })
}
