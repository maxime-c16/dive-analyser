#!/usr/bin/env python3
"""Generate DiveSensei trophies: catalog.json -> OpenSCAD -> STL (+ Blender renders).

Examples:
  python3 tools/trophies/build.py                       # every trophy, STL only
  python3 tools/trophies/build.py --only serie comeback --render
  python3 tools/trophies/build.py --only podium-or --owner "Léa M." --date 2026 --render
  python3 tools/trophies/build.py --render --lineup     # + group shot of all trophies
  python3 tools/trophies/build.py --sheet               # fast 2D review of every emblem

Outputs land in tools/trophies/out/<id>/ (git-ignored):
  <id>_socle.stl     plinth, print upright as-is
  <id>_embleme.stl   medallion, already lying flat (relief up)
  <id>_assemble.stl  both parts assembled, for preview only
  <id>.png           Blender render (with --render)
  review_sheet.png   flat emblem previews coloured by relief height (with --sheet)
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIB = HERE / "trophy.scad"
RENDER_SCRIPT = HERE / "render_blender.py"

# Layer shapes rendered by a plain module call with keyword args.
MODULE_SHAPES = {
    "wave", "water", "splash", "ripples", "star", "sparkle", "check", "flame",
    "diamond", "arc_arrow", "arrow", "chart", "bars", "tower", "springboard",
    "laurel", "peak", "circle",
}


def scad_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(scad_value(x) for x in v) + "]"
    raise TypeError(f"unsupported value {v!r}")


def layer_shape(layer: dict) -> str:
    shape = layer["shape"]
    args = layer.get("args", {})
    if shape == "diver":
        return f'diver({scad_value(layer["pose"])});'
    if shape == "text":
        size = args.get("size", 8)
        max_w = args.get("max_w", 44)
        return f'label({scad_value(layer["text"])}, {size}, {max_w});'
    if shape in MODULE_SHAPES:
        kw = ", ".join(f"{k} = {scad_value(v)}" for k, v in args.items())
        return f"{shape}({kw});"
    raise ValueError(f"unknown layer shape {shape!r} (add a module in trophy.scad)")


def layer_code(layer: dict) -> str:
    at = layer.get("at", [0, 0])
    rot = layer.get("rot", 0)
    s = layer.get("s", 1)
    sy = s * layer.get("scale_y", 1)
    h = layer.get("h", 1.8)
    return (f"    layer({h}) translate({scad_value(at)}) rotate({rot}) "
            f"scale([{s}, {sy}]) {layer_shape(layer)}")


def trophy_scad(t: dict) -> str:
    layers = "\n".join(layer_code(l) for l in t["layers"])
    socle_args = ", ".join(
        f"{k} = {scad_value(t[k])}" for k in ("title", "owner", "date", "brand"))
    return f"""// Generated by build.py from catalog.json - edit the catalog, not this file.
include <{LIB.as_posix()}>
part = "assemble"; // socle | embleme | assemble | embleme_pose

module this_emblem() {{
  emblem_plate() {{
{layers}
  }}
}}

if (part == "socle") socle({socle_args});
if (part == "embleme") this_emblem();
if (part == "embleme_pose") assembled_emblem() this_emblem();  // render input
if (part == "assemble") {{
  socle({socle_args});
  assembled_emblem() this_emblem();
}}
"""


def run(cmd: list[str]) -> None:
    res = subprocess.run(cmd, capture_output=True, text=True)
    errors = [l for l in res.stderr.splitlines() if "ERROR" in l or "WARNING" in l]
    if res.returncode != 0 or any("ERROR" in l for l in errors):
        sys.exit(f"command failed: {' '.join(cmd)}\n{res.stderr[-3000:]}")
    for l in errors:
        print(f"  {l}")


def build_trophy(t: dict, out: Path, openscad: str) -> Path:
    d = out / t["id"]
    d.mkdir(parents=True, exist_ok=True)
    scad = d / f"{t['id']}.scad"
    scad.write_text(trophy_scad(t), encoding="utf-8")
    for part in ("socle", "embleme", "assemble"):
        run([openscad, "-q", "-D", f'part="{part}"', "-o",
             str(d / f"{t['id']}_{part}.stl"), str(scad)])
    (d / "render").mkdir(exist_ok=True)
    run([openscad, "-q", "-D", 'part="embleme_pose"', "-o",
         str(d / "render" / "embleme_pose.stl"), str(scad)])
    (d / "meta.json").write_text(json.dumps(t, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"✓ {t['id']}")
    return d


def review_sheet(dirs: list[Path], out: Path, openscad: str) -> None:
    """Flat preview of every emblem (fast, no Blender) + a contact sheet."""
    def one(d: Path) -> Path:
        png = d / "render" / "review.png"
        run([openscad, "-q", "--preview", "-D", 'part="embleme"', "-D", "review=true",
             "--camera=0,55,200,0,55,0", "--projection=o", "--viewall",
             "--colorscheme=Tomorrow Night", "--imgsize=600,600",
             "-o", str(png), str(d / f"{d.name}.scad")])
        return png
    with ThreadPoolExecutor(4) as pool:
        pngs = list(pool.map(one, dirs))
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        print("Pillow missing: individual previews in <id>/render/review.png")
        return
    cols = 5
    rows = -(-len(pngs) // cols)
    sheet = Image.new("RGB", (600 * cols, 640 * rows), "#0d1113")
    draw = ImageDraw.Draw(sheet)
    for i, (d, png) in enumerate(zip(dirs, pngs)):
        x, y = (i % cols) * 600, (i // cols) * 640
        sheet.paste(Image.open(png), (x, y))
        draw.text((x + 20, y + 610), d.name, fill="#edf2f4")
    sheet.save(out / "review_sheet.png")
    print(f"✓ {out / 'review_sheet.png'}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--catalog", type=Path, default=HERE / "catalog.json")
    ap.add_argument("--out", type=Path, default=HERE / "out")
    ap.add_argument("--only", nargs="*", help="trophy ids to build")
    ap.add_argument("--owner", help="name engraved on the back (overrides catalog)")
    ap.add_argument("--date", help="date/season engraved on the back (overrides catalog)")
    ap.add_argument("--no-stl", action="store_true", help="skip OpenSCAD, reuse existing STL")
    ap.add_argument("--render", action="store_true", help="render each trophy with Blender")
    ap.add_argument("--lineup", action="store_true", help="render a group shot of the built trophies")
    ap.add_argument("--sheet", action="store_true", help="fast flat review sheet of the emblems")
    ap.add_argument("--samples", type=int, default=160)
    ap.add_argument("--jobs", type=int, default=4)
    args = ap.parse_args()

    catalog = json.loads(args.catalog.read_text(encoding="utf-8"))
    defaults = catalog.get("defaults", {})
    trophies = [{**defaults, **t} for t in catalog["trophies"]]
    if args.only:
        known = {t["id"] for t in trophies}
        missing = set(args.only) - known
        if missing:
            sys.exit(f"unknown trophy ids: {', '.join(sorted(missing))}")
        trophies = [t for t in trophies if t["id"] in args.only]
    for t in trophies:
        if args.owner is not None:
            t["owner"] = args.owner
        if args.date is not None:
            t["date"] = args.date

    openscad = shutil.which("openscad")
    if not openscad and not args.no_stl:
        sys.exit("openscad not found (brew install --cask openscad@snapshot)")

    if args.no_stl:
        dirs = [args.out / t["id"] for t in trophies]
    else:
        with ThreadPoolExecutor(args.jobs) as pool:
            dirs = list(pool.map(lambda t: build_trophy(t, args.out, openscad), trophies))

    if args.sheet:
        review_sheet(dirs, args.out, openscad)

    if args.render or args.lineup:
        blender = shutil.which("blender") or "/Applications/Blender.app/Contents/MacOS/Blender"
        cmd = [blender, "-b", "--factory-startup", "-P", str(RENDER_SCRIPT), "--",
               "--samples", str(args.samples)]
        if args.render:
            cmd += ["--each"]
        if args.lineup:
            cmd += ["--lineup", str(args.out / "lineup.png")]
        cmd += [str(d) for d in dirs]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            sys.exit(f"blender failed:\n{res.stdout[-3000:]}\n{res.stderr[-3000:]}")
        print("\n".join(l for l in res.stdout.splitlines() if l.startswith("[render]")))


if __name__ == "__main__":
    main()
